  private readonly languageSubject = new BehaviorSubject<string>(this.getStoredLanguage());
  readonly language$ = this.languageSubject.asObservable();

  constructor() {
    this.applyLanguage(this.getStoredLanguage(), false);
  }

  getStoredLanguage(): string {
    return localStorage.getItem(this.languageKey) ?? this.defaultLanguage;
  }

  setLanguage(language: string): void {
    this.languageSubject.next(language);
    this.applyLanguage(language, true);
  }

  translate(key: string): string {
    const selectedLanguage = this.languageSubject.value || this.defaultLanguage;
    return this.translations[selectedLanguage]?.[key] ?? this.translations[this.defaultLanguage][key] ?? key;
  }

  getCurrentLanguage(): string {
    return this.languageSubject.value || this.defaultLanguage;
  }

  private applyLanguage(language: string, persist: boolean): void {
    if (persist) {
      localStorage.setItem(this.languageKey, language);
    }

    this.languageSubject.next(language);
    document.documentElement.lang = this.getLocaleCode(language);
    document.documentElement.setAttribute('data-language', language);
  }

  private getLocaleCode(language: string): string {
    const map: Record<string, string> = {
      English: 'en',
      Kannada: 'kn',
      Hindi: 'hi',
      Telugu: 'te',
      Tamil: 'ta',
      Malayalam: 'ml',
    };

    return map[language] ?? 'en';
  }
